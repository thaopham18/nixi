// Command suggestions from history in a real local bash, and popups driven by the keyboard alone.
// POSIX shells only.
//   npm run build && node scripts/e2e-suggest.mjs
import { spawn } from 'child_process'
import { createHash } from 'crypto'
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'fs'
import { connect } from 'net'
import { tmpdir } from 'os'
import { join } from 'path'
import ssh2 from 'ssh2'
import { _electron as electron } from 'playwright-core'

let failed = 0
const check = (name, ok, detail = '') => {
  if (!ok) failed++
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${name} ${ok ? '' : detail}`)
}
const sleep = (ms) => new Promise((r) => setTimeout(r, ms))
const userData = mkdtempSync(join(tmpdir(), 'nixi-e2e-suggest-'))
const SSH = 2287
const sshd = spawn(process.execPath, ['scripts/dev-ssh-server.mjs', '--port', String(SSH)], { stdio: 'ignore' })
for (let i = 0; i < 100; i++) {
  const open = await new Promise((r) => {
    const c = connect(SSH, '127.0.0.1')
    c.once('connect', () => (c.destroy(), r(true)))
    c.once('error', () => r(false))
  })
  if (open) break
  await sleep(100)
}
for (let i = 0; i < 50 && !existsSync(join(tmpdir(), 'nixi-dev-hostkey')); i++) await sleep(100)
const hostKey = ssh2.utils.parseKey(readFileSync(join(tmpdir(), 'nixi-dev-hostkey')))
writeFileSync(join(userData, 'known_hosts.json'), JSON.stringify({ [`[127.0.0.1]:${SSH}`]: 'SHA256:' + createHash('sha256').update(hostKey.getPublicSSH()).digest('base64').replace(/=+$/, '') }))
writeFileSync(join(userData, 'secrets.json'), JSON.stringify({ s: 'raw:' + Buffer.from('test').toString('base64') }))
writeFileSync(
  join(userData, 'sessions.json'),
  JSON.stringify([
    { id: 'l', name: 'shell', type: 'local', folder: '' },
    { id: 's', name: 'remote', type: 'ssh', folder: '', host: '127.0.0.1', port: SSH, username: 'test', auth: 'password' }
  ])
)
writeFileSync(join(userData, 'settings.json'), JSON.stringify({ gpuRendering: false }))
const env = { ...process.env, NIXI_USER_DATA: userData, NIXI_TEST_PASSWORD: 'x-test' }

let app = await electron.launch({ args: ['.'], env })
try {
  let win = await app.firstWindow()
  await win.waitForSelector('.tree-row')
  const text = () => win.evaluate(() => [...document.querySelectorAll('.xterm-rows')].find((e) => e.getBoundingClientRect().width > 0)?.innerText ?? '')
  const until = async (fn, ms = 5000) => {
    const end = Date.now() + ms
    for (;;) {
      const v = await fn()
      if (v) return v
      if (Date.now() > end) return false
      await sleep(60)
    }
  }
  const sees = (re, ms) => until(async () => re.test(await text()), ms)
  const ghost = () => win.evaluate(() => {
    const g = [...document.querySelectorAll('.term-suggestion')].find((e) => !e.hidden && e.getBoundingClientRect().width > 0)
    return g?.textContent ?? ''
  })
  const ghostIs = (want) => until(async () => (await ghost()) === want, 1500)
  const key = (k) => win.keyboard.press(k)
  const type = (s) => win.keyboard.type(s)
  const clearLine = async () => {
    await key('Control+U')
    await ghostIs('')
  }
  const run = async (line) => {
    await type(line)
    await key('Enter')
    await sleep(250)
  }
  const startShell = async (name = 'shell') => {
    await win.locator('.tree-row', { hasText: new RegExp(`^${name}`) }).last().dblclick()
    await win.locator('.tab.active .dot.connected').waitFor({ timeout: 15000 })
    await win.locator('.tab-view:visible .term-container').first().click()
    await sleep(400)
    await run("exec bash --norc --noprofile")
    await run("PS1='$ '")
    await run('clear')
  }

  console.log('--- suggesting')
  await startShell()
  await run('echo first-one')
  await run('echo hello-nixi')
  await type('e')
  check('one letter: nothing yet', await ghostIs(''))
  await type('c')
  check('two letters: the newest match in grey', await ghostIs('ho hello-nixi'), await ghost())
  await sees(/\$ ec\s*$/) // the row is drawn a moment after the suggestion
  const box = await win.evaluate(() => {
    const g = [...document.querySelectorAll('.term-suggestion')].find((e) => !e.hidden)
    const r = g.getBoundingClientRect()
    const row = [...document.querySelectorAll('.xterm-rows > div')].find((d) => d.innerText.trim() === '$ ec')
    const typed = row?.getBoundingClientRect()
    return { left: r.left, top: r.top, rowTop: typed?.top, rowLeft: typed?.left }
  })
  check('…sits on the line being typed', box.rowTop !== undefined && Math.abs(box.top - box.rowTop) < 2, JSON.stringify(box))
  check('…right after the typed text', box.left > box.rowLeft + 10, JSON.stringify(box))
  check('…not part of the screen text', !/ho hello-nixi/.test((await text()).split('\n').pop() ?? ''))
  await win.screenshot({ path: join(tmpdir(), 'nixi-e2e-suggest.png') })
  await type('ho f')
  check('typing on narrows it', await ghostIs('irst-one'), await ghost())
  await key('Backspace')
  check('backspace widens it', await ghostIs('hello-nixi'), await ghost())
  await key('ArrowRight')
  check('→ takes it', await sees(/\$ echo hello-nixi\s*$/), await text())
  check('…nothing left to suggest', await ghostIs(''))
  await key('Enter')
  check('…Enter runs it', await sees(/\nhello-nixi\n/), await text())
  await type('echo f')
  await ghostIs('irst-one')
  await key('End')
  check('End takes it too', await sees(/\$ echo first-one\s*$/), await text())
  await clearLine()
  await type('zz')
  check('no match: nothing', await ghostIs(''))
  await key('ArrowRight')
  await clearLine()

  console.log('--- what is kept')
  await run('read -s ANSWER')
  await run('hunter-secret')
  await type('hu')
  check('a password typed with no echo is not kept', await ghostIs(''), await ghost())
  await clearLine()
  await run('echo --password=topsecret9 > /dev/null')
  await type('echo --')
  check('a command holding a secret is not kept', await ghostIs(''), await ghost())
  await clearLine()
  await run(' echo private-one')
  await type('echo pr')
  check('a leading space keeps it out', await ghostIs(''), await ghost())
  await clearLine()

  console.log('--- where it stays away')
  await run("printf 'x\\n' | less")
  await sleep(300)
  await type('ec')
  check('not inside less', await ghostIs(''), await ghost())
  await key('q')
  await sleep(200)
  await key('ArrowUp')
  await sleep(200)
  await type('ec')
  await clearLine()

  console.log('--- stays through Tab and ↑')
  await run('mkdir -p /tmp/nixi-e2e-tabdir && touch /tmp/nixi-e2e-tabdir/alpha.txt')
  await run('ls -la /tmp/nixi-e2e-tabdir/alpha.txt')
  await type('ls -la /tmp/nixi-e2e-tabd')
  check('before Tab', await ghostIs('ir/alpha.txt'), await ghost())
  await key('Tab')
  check('after Tab it still suggests the rest', await ghostIs('alpha.txt'), await ghost())
  await key('ArrowRight')
  check('→ takes it after Tab', await sees(/tabdir\/alpha\.txt\s*$/m), await text())
  await clearLine()
  await run('echo first-kept')
  await run('echo first-kept and more')
  await run('echo first-kept')
  await key('ArrowUp')
  check('after ↑ it suggests for the recalled line', await ghostIs(' and more'), await ghost())
  await clearLine()
  await run('rm -rf /tmp/nixi-e2e-tabdir')
  await sleep(100)

  console.log('--- a dialog with the keyboard')
  const focused = () => win.evaluate(() => document.activeElement?.textContent ?? '')
  const dialog = win.locator('.modal')
  await type('rm -rf /tmp/nixi-e2e-suggest-none')
  await key('Enter')
  await dialog.waitFor()
  check('starts on Cancel', (await focused()) === 'Cancel', await focused())
  await key('ArrowRight')
  check('→ moves to Run anyway', (await focused()) === 'Run anyway', await focused())
  await key('ArrowRight')
  check('→ goes round', (await focused()) === 'Cancel', await focused())
  await key('ArrowLeft')
  check('← goes back', (await focused()) === 'Run anyway', await focused())
  await key('Tab')
  await key('Tab')
  await key('Tab')
  check('Tab stays in the dialog', await win.evaluate(() => !!document.activeElement?.closest('.modal')))
  await win.locator('.modal-footer button', { hasText: 'Cancel' }).focus()
  await key('Enter')
  await dialog.waitFor({ state: 'detached' })
  check('Enter answers', (await dialog.count()) === 0)
  await sleep(150)
  await clearLine()
  await type('rm -rf /tmp/nixi-e2e-suggest-none')
  await key('Enter')
  await dialog.waitFor()
  await key('ArrowRight')
  await key('Enter')
  await dialog.waitFor({ state: 'detached' })
  await sleep(300)
  await type('rm')
  check('a dangerous command that ran is not suggested', await ghostIs(''), await ghost())
  await clearLine()

  console.log('--- a menu with the keyboard')
  const menu = win.locator('.context-menu')
  const active = () => win.locator('.context-menu .item.active').innerText().catch(() => '')
  const row = win.locator('.tree-row', { hasText: /^shell/ }).last()
  await row.click({ button: 'right' })
  await menu.waitFor()
  const labels = await win.locator('.context-menu .item:not(.disabled)').allInnerTexts()
  check('nothing chosen at first', (await active()) === '')
  await key('Enter')
  check('…so Enter does nothing', (await menu.count()) === 1)
  await key('ArrowDown')
  check('↓ picks the first', (await active()) === labels[0], await active())
  await key('ArrowDown')
  check('↓ the next', (await active()) === labels[1], await active())
  await key('ArrowUp')
  await key('ArrowUp')
  check('↑ goes round to the last', (await active()) === labels[labels.length - 1], await active())
  await key('Home')
  check('Home', (await active()) === labels[0])
  await key('End')
  check('End', (await active()) === labels[labels.length - 1])
  await key('Escape')
  check('Esc closes', (await menu.count()) === 0)
  await row.click({ button: 'right' })
  await menu.waitFor()
  await key('n')
  check('a letter jumps', /^n/i.test(await active()), await active())
  const chosen = await active()
  await key('Enter')
  check('Enter runs it', (await menu.count()) === 0)
  check('…and it did something', await until(async () => (await dialog.count()) === 1, 2000), chosen)
  await key('Escape')
  await dialog.waitFor({ state: 'detached' })

  await win.locator('.tab-view:visible .term-container').first().click()
  await sleep(200)
  await run('clear')
  const before = await text()
  const pane = win.locator('.tab.active').first()
  await pane.click({ button: 'right' })
  await menu.waitFor()
  await type('zq')
  await key('Escape')
  await win.locator('.tab-view:visible .term-container').first().click()
  await sleep(250)
  check('keys for the menu do not reach the terminal', !/zq/.test(await text()) && (await text()) === before, await text())

  console.log('--- stored')
  await app.close()
  const files = readdirSync(userData).filter((f) => f.endsWith('.nxdb'))
  const raw = files.map((f) => readFileSync(join(userData, f), 'latin1')).join('')
  check('the database file exists and hides commands', files.length > 0 && !raw.includes('hello-nixi'))
  app = await electron.launch({ args: ['.'], env })
  win = await app.firstWindow()
  await win.waitForSelector('.tree-row')
  await startShell()
  await type('echo h')
  check('history survives a restart', await ghostIs('ello-nixi'), await ghost())
  await clearLine()

  console.log('--- over SSH, with English-only keys')
  await startShell('remote')
  await type('echo h')
  check("another session's command is suggested", await ghostIs('ello-nixi'), await ghost())
  await key('ArrowRight')
  check('→ takes it', await sees(/\$ echo hello-nixi\s*$/), await text())
  await key('Enter')
  check('…and it runs on the server', await sees(/\nhello-nixi\n/), await text())
  await run('echo only-on-remote')
  await run('echo only-on-remote-2')
  await run('echo only-on-remote')
  await type('echo o')
  check('the newest use wins', await ghostIs('nly-on-remote'), await ghost())
  await clearLine()

  console.log('--- the setting')
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.send('menu:cmd', 'settings'))
  await win.locator('.settings-nav button', { hasText: 'Keyboard & Paste' }).click()
  await win.locator('.modal input[name=commandSuggestions]').uncheck()
  await win.locator('.modal-footer button.primary').click()
  await sleep(300)
  await win.locator('.tab-view:visible .term-container').first().click()
  await type('echo h')
  check('off: nothing shows', await ghostIs(''), await ghost())
  await key('ArrowRight')
  await clearLine()
  await run('echo while-off')
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.send('menu:cmd', 'settings'))
  await win.locator('.settings-nav button', { hasText: 'Keyboard & Paste' }).click()
  await win.locator('.modal input[name=commandSuggestions]').check()
  await win.locator('.modal-footer button.primary').click()
  await sleep(300)
  await win.locator('.tab-view:visible .term-container').first().click()
  await type('echo w')
  check('off: nothing was kept', await ghostIs(''), await ghost())
  await clearLine()
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].webContents.send('menu:cmd', 'settings'))
  await win.locator('.settings-nav button', { hasText: 'Keyboard & Paste' }).click()
  await win.locator('.modal button', { hasText: 'Clear history' }).click()
  await sleep(200)
  await key('Escape')
  await win.locator('.tab-view:visible .term-container').first().click()
  await type('echo h')
  check('Clear history empties it', await ghostIs(''), await ghost())
  await clearLine()
} finally {
  await app.close().catch(() => {})
  sshd.kill('SIGKILL')
  rmSync(userData, { recursive: true, force: true })
}
console.log(failed ? `${failed} FAILED` : 'All suggest checks passed')
process.exit(failed ? 1 : 0)
