describe('isReadOnlyCommand', () => {
  it.each(readOnly)('runs %s by itself', (cmd) => {
    expect(isReadOnlyCommand(cmd)).toBe(true)
  })

  it.each(asks)('asks about %s', (cmd) => {
    expect(isReadOnlyCommand(cmd)).toBe(false)
  })

  it('treats anything unknown as a reason to ask', () => {
    expect(isReadOnlyCommand('some-new-tool --list')).toBe(false)
    expect(isReadOnlyCommand('constructor')).toBe(false)
    expect(isReadOnlyCommand('__proto__ x')).toBe(false)
  })
})
